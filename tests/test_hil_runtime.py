ROOT = Path(__file__).resolve().parents[1]


class RuntimeInspectionTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.environment = Path(temporary.name) / "environment"
        self.site = self.environment / "Lib/site-packages"
        self.site.mkdir(parents=True)
        self.python = self.environment / "Scripts/python.exe"
        self.python.parent.mkdir()
        self.python.write_bytes(b"Not an executable; inspection must not start it")
        (self.environment / "pyvenv.cfg").write_text("version = 3.11.15\n")
        self.pin = hil.load_pin()
        for item in self.pin["files"]:
            path = self.site / item["path"]
            path.parent.mkdir(parents=True, exist_ok=True)
            data = ("synthetic payload: " + item["path"]).encode()
            if item["path"] == "hil_runner/__init__.py":
                data = b"raise AssertionError('never import during inspection')\n"
            path.write_bytes(data)
            item.update(size=len(data), sha256=hil.digest(data))
        self.addCleanup(mock.patch.stopall)
        mock.patch.object(hil, "load_pin", return_value=self.pin).start()
        self.native = self.environment.parent / "native-debugger.exe"
        self.native.write_bytes(b"synthetic debugger")
        self.pin["managed_debugger"]["sha256"] = hil.digest(self.native.read_bytes())

    def test_inspection_reads_pinned_files_without_execution_or_import(self):
        with mock.patch.object(
            subprocess, "run", side_effect=AssertionError("no process")
        ):
            report = hil.inspect_environment(self.environment)
        self.assertTrue(report["ok"], report)
        self.assertEqual(report["verified_files"], 19)
        self.assertFalse(report["executables_started"])
        self.assertFalse(report["hardware_access"])
        self.assertFalse(report["interpreter_version_verified"])
        self.assertFalse(report["authorization_granted"])

    def test_changed_source_fails_even_when_python_launcher_is_unchanged(self):
        source = self.site / "hil_runner/managed.py"
        source.write_bytes(source.read_bytes() + b"changed")
        report = hil.inspect_environment(self.environment)
        self.assertFalse(report["ok"])
        self.assertIn("Installed payload differs", report["errors"][0])

    def test_missing_schema_fails(self):
        (self.site / "hil_runner/schemas/managed-plan.schema.json").unlink()
        self.assertFalse(hil.inspect_environment(self.environment)["ok"])

    def test_extra_importable_module_fails(self):
        (self.site / "hil_runner/managed.pyd").write_bytes(
            b"unexpected native override"
        )
        report = hil.inspect_environment(self.environment)
        self.assertFalse(report["ok"])
        self.assertIn("Unexpected HIL package file", report["errors"][0])

    def test_ordinary_python_cache_is_not_mistaken_for_source_drift(self):
        cache = self.site / "hil_runner/__pycache__/managed.cpython-311.pyc"
        cache.parent.mkdir()
        cache.write_bytes(b"generated bytecode is outside the static payload check")
        self.assertTrue(hil.inspect_environment(self.environment)["ok"])

    def test_payload_symlink_is_rejected(self):
        source = self.site / "hil_runner/managed.py"
        outside = self.environment.parent / "outside.py"
        outside.write_bytes(source.read_bytes())
        source.unlink()
        try:
            source.symlink_to(outside)
        except OSError:
            self.skipTest("Symlink creation unavailable")
        self.assertFalse(hil.inspect_environment(self.environment)["ok"])

    def test_declared_old_python_is_rejected_without_starting_it(self):
        (self.environment / "pyvenv.cfg").write_text("version = 3.10.9\n")
        report = hil.inspect_environment(self.environment)
        self.assertFalse(report["ok"])
        self.assertIn("Python 3.11+", report["errors"][0])

    def test_uv_version_info_environment_is_supported(self):
        (self.environment / "pyvenv.cfg").write_text("version_info = 3.11.15\n")
        self.assertTrue(hil.inspect_environment(self.environment)["ok"])

    def test_relative_environment_is_rejected(self):
        self.assertFalse(hil.inspect_environment(Path("relative"))["ok"])

    def test_oversized_source_is_bounded(self):
        (self.site / "hil_runner/managed.py").write_bytes(b"x" * (1024 * 1024 + 1))
        report = hil.inspect_environment(self.environment)
        self.assertFalse(report["ok"])
        self.assertIn("size limit", report["errors"][0])

    def doctor_report(self, *, version="0.2.5", native_hash=None, platform="Windows"):
        if native_hash:
            self.pin["managed_debugger"]["sha256"] = native_hash
        component = next(
            item for item in doctor.COMPONENTS if item.name == "embedded-debugger"
        )
        checked = {
            "name": component.name,
            "ok": True,
            "status": "ready",
            "executable": str(self.native),
            "version": version,
        }
        with (
            mock.patch.object(doctor, "check_component", return_value=checked),
            mock.patch.object(
                doctor, "check_plugin_layout", return_value={"ok": True, "errors": []}
            ),
            mock.patch.object(doctor.platform, "system", return_value=platform),
            mock.patch.object(
                subprocess, "run", side_effect=AssertionError("no HIL process")
            ),
        ):
            return doctor.build_report(
                [component], 1, ROOT, hil_environment=self.environment
            )

    def test_doctor_accepts_matching_payload_and_qualified_debugger(self):
        report = self.doctor_report()
        self.assertTrue(report["complete"], report)
        self.assertTrue(report["hil_runner"]["native_debugger_verified"])
        self.assertEqual(
            report["hil_runner"]["resolution_source"], "pinned_distribution"
        )

    def test_doctor_does_not_accept_old_selected_debugger(self):
        report = self.doctor_report(version="0.2.4")
        self.assertFalse(report["ok"])
        self.assertFalse(report["hil_runner"]["native_debugger_verified"])
        self.assertEqual(report["hil_runner"]["verified_files"], 19)

    def test_doctor_detects_same_version_different_debugger_bytes(self):
        report = self.doctor_report(native_hash="0" * 64)
        self.assertFalse(report["complete"])

    def test_doctor_rejects_non_windows_managed_runtime(self):
        self.assertFalse(self.doctor_report(platform="Linux")["ok"])


class PinAndCliTests(unittest.TestCase):
    def test_dangerous_or_duplicate_pin_paths_fail_before_file_access(self):
        original = hil.load_pin()
        for name in (
            "../escape",
            "/absolute",
            "hil_runner/COM3",
            "hil_runner/AUX.txt",
            "hil_runner/a:stream",
            "hil_runner/a\\b.py",
            "hil_runner/a.",
            original["files"][0]["path"].upper(),
        ):
            with self.subTest(name=name):
                pin = copy.deepcopy(original)
                pin["files"].append({"path": name, "size": 0, "sha256": "a" * 64})
                with self.assertRaises(ValueError):
                    hil.parse_pin(json.dumps(pin).encode())

    def test_duplicate_json_keys_are_rejected(self):
        with self.assertRaises(ValueError):
            hil.parse_pin(b'{"version":"0.2.0","version":"0.3.0"}')

    def test_cli_failure_is_json_and_does_not_create_environment(self):
        with tempfile.TemporaryDirectory() as directory:
            missing = Path(directory) / "missing"
            completed = subprocess.run(
                [
                    sys.executable,
                    "-B",
                    str(ROOT / "scripts/hil_runtime.py"),
                    "inspect",
                    str(missing),
                    "--json",
                ],
                capture_output=True,
                check=False,
                timeout=5,
            )
            self.assertEqual(completed.returncode, 2)
            report = json.loads(completed.stdout)
            self.assertFalse(report["executables_started"])
            self.assertFalse(missing.exists())
            self.assertFalse(completed.stderr)

    def test_default_doctor_does_not_discover_or_inspect_hil(self):
        with (
            mock.patch.object(
                hil, "inspect_environment", side_effect=AssertionError("not requested")
            ),
            mock.patch.object(
                doctor, "check_plugin_layout", return_value={"ok": True, "errors": []}
            ),
        ):
            report = doctor.build_report([], 1, ROOT)
        self.assertTrue(report["ok"])
        self.assertNotIn("hil_runner", report)
